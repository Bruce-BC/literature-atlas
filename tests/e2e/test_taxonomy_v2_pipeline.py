def luminance(hex_color: str) -> float:
    channels = [int(hex_color[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    channels = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * channels[0] + 0.7152 * channels[1] + 0.0722 * channels[2]


def contrast(a: str, b: str) -> float:
    x, y = luminance(a), luminance(b)
    return (max(x, y) + 0.05) / (min(x, y) + 0.05)


def label_of(entity: dict[str, Any], fallback: str) -> str:
    label = entity.get("label")
    return label if isinstance(label, str) else (label or {}).get("en") or (label or {}).get("ko") or fallback


def entities_by_any_id(snapshot: dict[str, Any]) -> dict[str, dict[str, Any]]:
    result: dict[str, dict[str, Any]] = {}
    for entity in snapshot["facetCatalog"]["entities"]:
        result[entity["id"]] = entity
        if entity.get("facetId"):
            result[entity["facetId"]] = entity
    return result


def expected_facet_rows(snapshot: dict[str, Any], paper_id: str) -> dict[str, str]:
    """Detail rows the UI must show, derived ONLY from the API payload (mirrors the documented row format)."""
    row = next(item for item in snapshot["paperFacets"] if item["paperId"] == paper_id)
    entities = entities_by_any_id(snapshot)
    primary = {value for value in row["primaryByFacet"].values() if value}
    by_kind: dict[str, list[str]] = {}
    for membership in row["directMemberships"]:
        entity = entities.get(membership["facetId"], {})
        kind = membership.get("kind") or entity.get("kind") or "facet"
        tier = (membership.get("evidenceRef") or {}).get("evidenceTier") or membership.get("origin")
        text = label_of(entity, membership["facetId"]) + (" ★ primary" if membership["facetId"] in primary else "") + (f" · {tier}" if tier else "")
        by_kind.setdefault(kind, []).append(text)
    return {kind.capitalize(): "; ".join(by_kind[kind]) for kind in ("subject", "method", "tool", "application") if kind in by_kind}


def detail_rows(app: Pipeline) -> dict[str, str]:
    return app.h.page.evaluate("() => Object.fromEntries([...document.querySelectorAll('#atlas-detail dl dt')].map(dt => [dt.textContent, dt.nextElementSibling?.textContent ?? '']))")


def paper_title(snapshot: dict[str, Any], paper_id: str) -> str:
    return next(p["title"] for p in snapshot["papers"] if p["id"] == paper_id)


def open_all_papers(app: Pipeline, expected: int) -> None:
    app.h.page.locator("#atlas-overview-renderer").select_option("all-papers")
    app.h.overview_ready(expected)


def select_point(app: Pipeline, paper_id: str) -> None:
    app.h.click_node("overview", f"overview-paper:{paper_id}")
    app.h.wait("id => window.AtlasDebug.getViewState()?.selected?.id === id", 10, paper_id)


def snapshot_in_browser(app: Pipeline) -> dict[str, Any]:
    return app.h.page.evaluate("() => { const s = window.AtlasDebug.getState().snapshot; return {serverId: s.source.serverId, epoch: s.source.epoch, revision: s.revision, status: s.modelStatus?.status, recipe: s.modelStatus?.recipeVersion, papers: s.papers.map(p => p.id)}; }")


