def test_generated_qiime2_and_phage_facets_colors_and_counts_reach_the_browser_from_the_real_backend():
    with running_pipeline(qiime_items) as app:
        snapshot = app.snapshot()
        FIXTURE_VALIDATION.clear()
        _NOTES["apiSnapshotValidation"] = validate_fixture(snapshot)  # strict JSON schema + frontend decodeSnapshot on REAL generated output
        ids = {"qiime": app.source.paper_id("QIIME01"), "phage": app.source.paper_id("PHAGE01")}
        entities = entities_by_any_id(snapshot)
        facets = {row["paperId"]: row for row in snapshot["paperFacets"]}
        def primary_label(paper: str, kind: str) -> str:
            return label_of(entities[facets[ids[paper]]["primaryByFacet"][kind]], "")
        # reviewed domain contract, read back from generated output
        assert primary_label("qiime", "subject") == "Bioinformatics" and primary_label("qiime", "tool") == "QIIME 2"
        assert "Amplicon" in primary_label("qiime", "method")
        assert primary_label("phage", "subject") == "Phage Biology" and primary_label("phage", "tool") == "QIIME 2"
        phage_kinds = {m["kind"] for m in facets[ids["phage"]]["directMemberships"]}
        assert "method" not in phage_kinds, "QIIME2 usage alone must not create a method facet for the phage paper"
        # ---- browser: native point clicks, detail rows must equal what the API generated ----
        open_all_papers(app, 2)
        for name, paper_id in ids.items():
            select_point(app, paper_id)
            app.h.wait("t => document.querySelector('.atlas-selection-detail h3')?.textContent === t", 10, paper_title(snapshot, paper_id))
            rows = detail_rows(app)
            expected = expected_facet_rows(snapshot, paper_id)
            assert {key: rows.get(key) for key in expected} == expected, f"{name}: facet rows differ from API"
            assert set(expected) >= {"Subject", "Tool", "Application"} and "★ primary" in expected["Subject"] and "★ primary" in expected["Tool"]
            lower = app.h.page.evaluate("() => [window.AtlasDebug.getLowerProjection().revision, window.AtlasDebug.getViewState().revision]")
            assert lower[0] == lower[1]
        assert set(expected_facet_rows(snapshot, ids["qiime"])) == {"Subject", "Method", "Tool", "Application"}, "typed four-facet detail for the QIIME2 + amplicon paper"
        # ---- legend counts come from the API fieldStats ----
        stats = {row["fieldId"]: row for row in snapshot["fieldStats"]["rows"]}
        dom = app.h.page.evaluate("() => Object.fromEntries([...document.querySelectorAll('#atlas-field-legend button[data-field-id]')].map(b => [b.dataset.fieldId, [[...b.querySelectorAll('.atlas-legend-number')].map(n => Number(n.textContent)), b.querySelector('.atlas-legend-swatch').dataset.categoryColor]]))")
        assert set(dom) == set(stats), "legend rows must be exactly the API fields"
        for field_id, row in stats.items():
            assert dom[field_id][0] == [row["direct"], row["inclusive"]], f"legend counts for {field_id[-20:]} differ from API fieldStats"
        caption = app.h.page.locator("#atlas-field-legend .atlas-field-legend-caption").inner_text()
        assert f"Known primary {snapshot['fieldStats']['knownPrimary']} + unknown {snapshot['fieldStats']['unknown']} = {snapshot['fieldStats']['paperCount']} papers" in caption
        # ---- category colours come from the backend registry (contrast-floor aware) ----
        registry = snapshot["categoryColorRegistry"]["entries"]
        checked = 0
        for field in snapshot["fields"]:
            entity = next((e for e in snapshot["facetCatalog"]["entities"] if e.get("legacyFieldId") == field["id"]), None)
            keys = {field["id"]} | ({entity.get("facetId"), entity.get("ontologyKey"), entity["id"]} if entity else set())
            entry = next((item for item in registry if item["categoryKey"] in keys or item["ontologyKey"] in keys), None)
            if not entry:
                continue
            expected_hex = entry["hexByPaletteTheme"].get("atlas:light") or entry["hexByPaletteTheme"]["light"]
            if contrast(expected_hex, "#ffffff") >= 3:
                assert dom[field["id"]][1].lower() == expected_hex.lower(), f"{field['id'][-20:]}: legend colour differs from backend registry"
                checked += 1
        assert checked >= 3, "registry colours were not verified for enough categories"
        _NOTES["registryColoursVerified"] = checked
        shot(app, "pipeline-generated-facets-1440-light")
        assert not app.h.errors, app.h.errors[:3]


