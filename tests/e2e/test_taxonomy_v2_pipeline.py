def _retained(snapshot: dict[str, Any]) -> dict[str, Any]:
    """What must never depend on the display sample: concepts, quality ledger, memberships, keyword aggregate."""
    return {
        "concepts": sorted(c["id"] for c in snapshot["concepts"]),
        "ledger": snapshot["conceptQualityLedger"],
        "memberships": sorted((m["paperId"], m["fieldId"], m.get("method")) for m in snapshot["memberships"]),
        "aggregate": snapshot["overview"]["keywordAggregate"],
        "paperFacets": sorted(row["paperId"] for row in snapshot["paperFacets"]),
    }


def _canon(value: Any) -> str:
    return json.dumps(value, sort_keys=True)


